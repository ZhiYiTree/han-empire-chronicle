def main():
    p = os.path.join(OUT, "events.json")
    events = json.load(open(p, encoding="utf-8"))
    n = 0
    for e in events:
        if e.get("summary"):
            continue
        s = SIMPLE.get(e["id"])
        if not s:
            continue
        e["summary"], e["story"] = s[0], s[1]
        e.setdefault("shiji", [])
        e.setdefault("analysis", "")
        e.setdefault("claimType", "primary_source_record")
        n += 1
    json.dump(events, open(p, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    miss = [e["id"] for e in events if not e.get("summary")]
    print(f"补齐摘要 {n} 条，仍缺 {len(miss)} 条", miss)

    # 打包为 data.js
    data = {}
    for name in ("persons", "events", "relations", "lectures", "sources", "traits"):
        data[name] = json.load(open(os.path.join(OUT, name + ".json"), encoding="utf-8"))
    js = "window.HAN_DATA=" + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";"
    fp = os.path.join(SITE, "data.js")
    open(fp, "w", encoding="utf-8").write(js)
    print(f"data.js {os.path.getsize(fp)//1024} KB")
    for k, v in data.items():
        print(f"  {k}: {len(v)}")


if __name__ == "__main__":
    main()
